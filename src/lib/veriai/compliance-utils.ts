/**
 * Pure, client-safe validity/status helpers for the SIH26262 compliance
 * modules. Shared by server functions and UI so both derive identical states.
 */

/** Document validity is always derived from stored dates — never guessed. */
export function deriveValidityStatus(input: {
  expiryDate: string | null | undefined;
  validityStatus?: string | null | undefined;
  verifiedAt?: string | null | undefined;
}): "valid" | "expiring_soon" | "expired" {
  const explicit = input.validityStatus;
  if (explicit === "renewed" || explicit === "correction_required" || explicit === "renewal_submitted") {
    return explicit === "renewed" ? "valid" : "expired";
  }
  if (!input.expiryDate) return "valid";
  const days = Math.ceil(
    (new Date(input.expiryDate + "T00:00:00").getTime() - Date.now()) / 86_400_000,
  );
  if (days < 0) return "expired";
  if (days <= 90) return "expiring_soon"; // demo reminder horizon, configurable
  return "valid";
}

/** Undertaking display status, derived when the stored status is still base. */
export function deriveUndertakingStatus(input: {
  status: string | null | undefined;
  dueDate: string | null | undefined;
  submissionCount?: number | null;
}): string {
  const stored = input.status ?? "upcoming";
  if (
    stored === "complied" ||
    stored === "correction_required" ||
    stored === "under_verification" ||
    stored === "escalated"
  ) {
    return stored;
  }
  if (!input.dueDate) return stored === "submitted" ? "submitted" : "pending_submission";
  const days = Math.ceil(
    (new Date(input.dueDate + "T00:00:00").getTime() - Date.now()) / 86_400_000,
  );
  if (days < 0 && stored !== "submitted" && stored !== "under_verification") return "overdue";
  if (stored === "submitted") return "submitted";
  if (days <= 30) return "due_soon";
  return "upcoming";
}

